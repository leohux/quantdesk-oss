@dataclass
class ComparisonReport:
    """Statistical comparison between two return series."""
    shadow_return_pct: float = 0.0
    benchmark_return_pct: float = 0.0
    shadow_sharpe: float = 0.0
    benchmark_sharpe: float = 0.0
    shadow_max_dd: float = 0.0
    benchmark_max_dd: float = 0.0
    correlation: float = 0.0
    tracking_error: float = 0.0
    alpha: float = 0.0
    beta: float = 0.0

    def to_dict(self) -> dict[str, Any]:
        return {
            "shadow_return_pct": round(self.shadow_return_pct, 4),
            "benchmark_return_pct": round(self.benchmark_return_pct, 4),
            "shadow_sharpe": round(self.shadow_sharpe, 4),
            "benchmark_sharpe": round(self.benchmark_sharpe, 4),
            "shadow_max_dd": round(self.shadow_max_dd, 4),
            "benchmark_max_dd": round(self.benchmark_max_dd, 4),
            "correlation": round(self.correlation, 4),
            "tracking_error": round(self.tracking_error, 4),
            "alpha": round(self.alpha, 6),
            "beta": round(self.beta, 4),
        }


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _max_drawdown(equity: pd.Series) -> float:
    """Maximum drawdown as a negative fraction (e.g. -0.15 = -15%)."""
    if equity.empty:
        return 0.0
    cummax = equity.cummax()
    dd = (equity - cummax) / cummax.replace(0, np.nan)
    return float(dd.min()) if not dd.empty else 0.0


def _sharpe(returns: pd.Series, periods_per_year: int = 252) -> float:
    """Annualised Sharpe ratio (risk-free rate assumed 0)."""
    if returns.empty or returns.std() == 0:
        return 0.0
    return float(returns.mean() / returns.std() * np.sqrt(periods_per_year))


def _compute_comparison(
    shadow_equity: pd.Series,
    benchmark_equity: pd.Series,
) -> ComparisonReport:
    """Core statistical comparison between two equity curves."""
    # Align on common index
    combined = pd.DataFrame({
        "shadow": shadow_equity,
        "benchmark": benchmark_equity,
    }).dropna()
    if combined.empty:
        return ComparisonReport()

    shadow_ret = combined["shadow"].pct_change().dropna()
    bench_ret = combined["benchmark"].pct_change().dropna()

    # Align returns
    min_len = min(len(shadow_ret), len(bench_ret))
    shadow_ret = shadow_ret.iloc[:min_len]
    bench_ret = bench_ret.iloc[:min_len]

    report = ComparisonReport()

    # Total return %
    report.shadow_return_pct = (combined["shadow"].iloc[-1] / combined["shadow"].iloc[0] - 1) * 100
    report.benchmark_return_pct = (combined["benchmark"].iloc[-1] / combined["benchmark"].iloc[0] - 1) * 100

    # Sharpe
    report.shadow_sharpe = _sharpe(shadow_ret)
    report.benchmark_sharpe = _sharpe(bench_ret)

    # Max drawdown
    report.shadow_max_dd = _max_drawdown(combined["shadow"]) * 100
    report.benchmark_max_dd = _max_drawdown(combined["benchmark"]) * 100

    # Correlation
    if min_len > 1:
        report.correlation = float(shadow_ret.corr(bench_ret))

        # Tracking error (annualised std of return differences)
        diff = shadow_ret.values - bench_ret.values
        report.tracking_error = float(np.std(diff) * np.sqrt(252)) * 100

        # CAPM alpha & beta
        cov_matrix = np.cov(shadow_ret.values, bench_ret.values)
        bench_var = cov_matrix[1, 1]
        if bench_var > 0:
            report.beta = float(cov_matrix[0, 1] / bench_var)
            report.alpha = (
                float(shadow_ret.mean() - report.beta * bench_ret.mean()) * 252 * 100
            )

    return report


