"""Shadow Trading Module.

Runs strategy signals alongside real market data WITHOUT sending real orders.
Generates theoretical orders, tracks theoretical positions/PnL, and produces
comparison reports against backtest results or buy-and-hold benchmarks.
"""
from __future__ import annotations

import logging
import threading
import uuid
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any

import numpy as np
import pandas as pd

from core.strategy.engine import run_signal_fn

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Data classes
# ---------------------------------------------------------------------------

@dataclass
class TheoreticalOrder:
    """A paper order generated by shadow trading — never sent to a broker."""
    id: str = field(default_factory=lambda: uuid.uuid4().hex[:12])
    symbol: str = ""
    side: str = "buy"           # "buy" | "sell"
    qty: float = 0.0
    price: float = 0.0
    timestamp: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    signal_reason: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "symbol": self.symbol,
            "side": self.side,
            "qty": self.qty,
            "price": round(self.price, 4),
            "timestamp": self.timestamp.isoformat(),
            "signal_reason": self.signal_reason,
        }


@dataclass
class _ShadowPosition:
    """Internal position tracker for a single symbol."""
    symbol: str
    qty: float = 0.0
    avg_cost: float = 0.0
    current_price: float = 0.0
    realized_pnl: float = 0.0

    @property
    def market_value(self) -> float:
        return self.qty * self.current_price

    @property
    def unrealized_pnl(self) -> float:
        if self.qty <= 0:
            return 0.0
        return (self.current_price - self.avg_cost) * self.qty

    def update_price(self, price: float) -> None:
        self.current_price = price


# ---------------------------------------------------------------------------
# TheoreticalPortfolio
# ---------------------------------------------------------------------------

class TheoreticalPortfolio:
    """Paper portfolio that tracks cash, positions, and PnL without real orders."""

    def __init__(self, init_cash: float = 100_000.0) -> None:
        self._init_cash = init_cash
        self._cash = init_cash
        self._positions: dict[str, _ShadowPosition] = {}
        self._orders: list[TheoreticalOrder] = []

    # -- properties ----------------------------------------------------------

    @property
    def cash(self) -> float:
        return self._cash

    @property
    def invested(self) -> float:
        return sum(p.market_value for p in self._positions.values())

    @property
    def equity(self) -> float:
        return self._cash + self.invested

    @property
    def pnl(self) -> float:
        return self.equity - self._init_cash

    @property
    def positions(self) -> dict[str, _ShadowPosition]:
        return dict(self._positions)

    # -- mutations -----------------------------------------------------------

    def open_position(self, symbol: str, qty: float, price: float, timestamp: datetime | None = None) -> TheoreticalOrder:
        """Buy *qty* shares of *symbol* at *price*."""
        symbol = symbol.upper()
        cost = qty * price
        if cost > self._cash:
            raise ValueError(
                f"Insufficient cash: need {cost:.2f} but have {self._cash:.2f}"
            )
        self._cash -= cost

        pos = self._positions.get(symbol)
        if pos is None:
            pos = _ShadowPosition(symbol=symbol)
            self._positions[symbol] = pos

        total_qty = pos.qty + qty
        if total_qty > 0:
            pos.avg_cost = (pos.avg_cost * pos.qty + price * qty) / total_qty
        pos.qty = total_qty
        pos.update_price(price)

        order = TheoreticalOrder(
            symbol=symbol,
            side="buy",
            qty=qty,
            price=price,
            timestamp=timestamp or datetime.now(timezone.utc),
            signal_reason="open",
        )
        self._orders.append(order)
        return order

    def close_position(self, symbol: str, qty: float, price: float, timestamp: datetime | None = None) -> TheoreticalOrder:
        """Sell *qty* shares of *symbol* at *price*."""
        symbol = symbol.upper()
        pos = self._positions.get(symbol)
        if pos is None or pos.qty < qty:
            have = pos.qty if pos else 0.0
            raise ValueError(f"Insufficient position: {symbol} (have {have}, need {qty})")

        realized = (price - pos.avg_cost) * qty
        pos.realized_pnl += realized
        self._cash += qty * price
        pos.qty -= qty
        if pos.qty <= 0:
            del self._positions[symbol]
        else:
            pos.update_price(price)

        order = TheoreticalOrder(
            symbol=symbol,
            side="sell",
            qty=qty,
            price=price,
            timestamp=timestamp or datetime.now(timezone.utc),
            signal_reason="close",
        )
        self._orders.append(order)
        return order

    def update_prices(self, prices: dict[str, float]) -> None:
        """Mark-to-market all held positions."""
        for symbol, pos in self._positions.items():
            if symbol in prices:
                pos.update_price(prices[symbol])

    def get_theoretical_orders(self) -> list[TheoreticalOrder]:
        """Return all generated orders (read-only copy)."""
        return list(self._orders)


