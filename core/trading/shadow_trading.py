# ShadowTrader
# ---------------------------------------------------------------------------

class ShadowTrader:
    """Shadow-trading engine: runs strategy signals in real-time without real orders.

    Parameters
    ----------
    strategy_code : str
        Python source code with a ``generate_signals(close, params)`` function.
    params : dict
        Strategy parameters forwarded to the signal function.
    symbols : list[str]
        Tickers to track.
    init_cash : float
        Starting theoretical cash.
    sizing_pct : float
        Fraction of equity to allocate per position (default 10%).
    """

    def __init__(
        self,
        strategy_code: str,
        params: dict[str, Any],
        symbols: list[str],
        init_cash: float = 100_000.0,
        sizing_pct: float = 0.10,
    ) -> None:
        self._strategy_code = strategy_code
        self._params = params or {}
        self._symbols = [s.upper() for s in symbols]
        self._init_cash = init_cash
        self._sizing_pct = sizing_pct

        self._portfolio = TheoreticalPortfolio(init_cash=init_cash)
        self._running = False
        self._lock = threading.RLock()

        # Per-symbol close-price buffers for signal generation
        self._buffers: dict[str, pd.Series] = {
            s: pd.Series(dtype=float) for s in self._symbols
        }

        # Equity curve: list of (timestamp, equity) tuples
        self._equity_curve: list[dict[str, Any]] = []

    # -- lifecycle -----------------------------------------------------------

    def start(self) -> None:
        """Begin accepting bars."""
        with self._lock:
            if self._running:
                return
            # Validate strategy code eagerly
            run_signal_fn(pd.Series(dtype=float), self._strategy_code, self._params)
            self._running = True
            logger.info("ShadowTrader started for %s", self._symbols)

    def stop(self) -> None:
        """Stop accepting bars."""
        with self._lock:
            self._running = False
            logger.info("ShadowTrader stopped")

    @property
    def is_running(self) -> bool:
        return self._running

    # -- bar processing ------------------------------------------------------

    def process_bar(self, bar: dict[str, Any]) -> TheoreticalOrder | None:
        """Process a single OHLCV bar and return a theoretical order if signalled.

        Expected bar keys: ``symbol``, ``close`` (float). Optional: ``timestamp``.
        """
        if not self._running:
            return None

        symbol: str = bar.get("symbol", "").upper()
        close_val: float | None = bar.get("close")
        timestamp = bar.get("timestamp")

        if not symbol or close_val is None:
            raise ValueError("Bar must contain 'symbol' and 'close'")
        if symbol not in self._symbols:
            return None

        with self._lock:
            # Accumulate close prices
            buf = self._buffers[symbol]
            new_point = pd.Series([float(close_val)])
            self._buffers[symbol] = buf = pd.concat([buf, new_point]).tail(500)

            # Need at least a few bars for signals
            if len(buf) < 5:
                self._snapshot_equity(timestamp)
                return None

            # Update portfolio prices
            self._portfolio.update_prices({symbol: float(close_val)})

            # Generate signals
            try:
                entries, exits = run_signal_fn(buf, self._strategy_code, self._params)
            except Exception as exc:
                logger.error("ShadowTrader signal error for %s: %s", symbol, exc)
                self._snapshot_equity(timestamp)
                return None

            has_entry = bool(entries.iloc[-1]) if len(entries) > 0 else False
            has_exit = bool(exits.iloc[-1]) if len(exits) > 0 else False

            ts = timestamp if isinstance(timestamp, datetime) else datetime.now(timezone.utc)
            order: TheoreticalOrder | None = None

            if has_exit and symbol in self._portfolio.positions:
                pos = self._portfolio.positions[symbol]
                order = self._portfolio.close_position(
                    symbol, pos.qty, float(close_val), ts,
                )
                order.signal_reason = "exit_signal"
                logger.info("Shadow EXIT %s qty=%.2f @ %.2f", symbol, pos.qty, close_val)

            elif has_entry and symbol not in self._portfolio.positions:
                equity = self._portfolio.equity
                alloc = equity * self._sizing_pct
                qty = int(alloc / float(close_val))
                if qty > 0:
                    try:
                        order = self._portfolio.open_position(
                            symbol, qty, float(close_val), ts,
                        )
                        order.signal_reason = "entry_signal"
                        logger.info(
                            "Shadow ENTRY %s qty=%d @ %.2f", symbol, qty, close_val,
                        )
                    except ValueError as exc:
                        logger.warning("Shadow open_position skipped: %s", exc)

            self._snapshot_equity(ts)
            return order

    # -- state & analytics ---------------------------------------------------

    def get_shadow_state(self) -> dict[str, Any]:
        """Return full shadow-trading state snapshot."""
        with self._lock:
            return {
                "equity": round(self._portfolio.equity, 2),
                "cash": round(self._portfolio.cash, 2),
                "pnl": round(self._portfolio.pnl, 2),
                "positions": {
                    sym: {
                        "qty": p.qty,
                        "avg_cost": round(p.avg_cost, 4),
                        "current_price": round(p.current_price, 4),
                        "market_value": round(p.market_value, 2),
                        "unrealized_pnl": round(p.unrealized_pnl, 2),
                        "realized_pnl": round(p.realized_pnl, 2),
                    }
                    for sym, p in self._portfolio.positions.items()
                },
                "orders_count": len(self._portfolio.get_theoretical_orders()),
                "running": self._running,
                "symbols": list(self._symbols),
            }

    def get_equity_curve(self) -> list[dict[str, Any]]:
        """Return list of {timestamp, equity} dicts."""
        with self._lock:
            return list(self._equity_curve)

    def get_theoretical_orders(self) -> list[TheoreticalOrder]:
        """Return all generated orders."""
        with self._lock:
            return self._portfolio.get_theoretical_orders()

    # -- comparison ----------------------------------------------------------

    @staticmethod
    def compare_with_backtest(
        shadow_results: dict[str, Any],
        backtest_results: dict[str, Any],
    ) -> ComparisonReport:
        """Compare shadow equity curve with a backtest equity curve.

        Both inputs should contain ``equity_curve`` as a list of dicts with
        ``timestamp`` and ``equity`` keys.
        """
        shadow_eq = _equity_from_results(shadow_results)
        backtest_eq = _equity_from_results(backtest_results)
        return _compute_comparison(shadow_eq, backtest_eq)

    @staticmethod
    def compare_with_buyhold(
        shadow_results: dict[str, Any],
        benchmark_data: pd.Series | dict[str, Any],
    ) -> ComparisonReport:
        """Compare shadow equity curve with a buy-and-hold benchmark.

        ``benchmark_data`` can be a pd.Series of prices or a dict with an
        ``equity_curve`` key.
        """
        shadow_eq = _equity_from_results(shadow_results)
        if isinstance(benchmark_data, pd.Series):
            bench_eq = benchmark_data.sort_index()
        else:
            bench_eq = _equity_from_results(benchmark_data)
        return _compute_comparison(shadow_eq, bench_eq)

    # -- internal helpers ----------------------------------------------------

    def _snapshot_equity(self, timestamp: datetime | None = None) -> None:
        """Append current equity to the curve."""
        self._equity_curve.append({
            "timestamp": (timestamp or datetime.now(timezone.utc)).isoformat()
            if isinstance(timestamp, datetime)
            else str(timestamp),
            "equity": round(self._portfolio.equity, 2),
            "cash": round(self._portfolio.cash, 2),
        })


# ---------------------------------------------------------------------------
# Private helpers
# ---------------------------------------------------------------------------

def _equity_from_results(results: dict[str, Any]) -> pd.Series:
    """Extract a pd.Series equity curve from a results dict."""
    curve = results.get("equity_curve", [])
    if not curve:
        raise ValueError("Results must contain a non-empty 'equity_curve'")

    if isinstance(curve, pd.Series):
        return curve

    equities = [point["equity"] for point in curve]
    timestamps = [point.get("timestamp", i) for i, point in enumerate(curve)]
    return pd.Series(equities, index=timestamps, dtype=float)
